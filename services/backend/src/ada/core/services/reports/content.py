"""The component tree of a report and of a report template.

A plain JSON tree (docs/spec.md, "OpenUI"): a document of blocks. Static blocks (heading,
text, callout, section) hold words only; the widget block is the one component that shows
data, and it names a widget, never values. Every write is checked here, so a stored tree
always has this shape:

    {"blocks": [
        {"type": "heading", "text": "Screening gap", "level": 1},
        {"type": "text", "text": "Plain text; a blank line starts a new paragraph."},
        {"type": "callout", "tone": "finding", "title": "Gap", "text": "..."},
        {"type": "widget", "widget_id": "<uuid>", "caption": "optional words"},
        {"type": "section", "title": "Trend", "blocks": [...]}
    ]}

In a template a widget block names a `slot` instead of a `widget_id`. A stored report
version also carries `sources`, which the platform generates (sources.py); a caller never
writes it.
"""

from collections.abc import Iterator, Mapping, Sequence
from enum import StrEnum
from typing import Annotated, Any, Literal

from pydantic import BaseModel, ConfigDict, Field, TypeAdapter, ValidationError

from ada.core.models.base import Id, JsonObject
from ada.core.models.errors import Invalid

# Bounds that keep a tree a document rather than a data dump.
MAX_BLOCKS = 500
MAX_DEPTH = 4
MAX_TEXT = 20_000

# Written by the platform into a stored version; refused in what a caller sends.
SOURCES_KEY = "sources"
BLOCKS_KEY = "blocks"


class _Block(BaseModel):
    # A key a block does not define is refused, so no data can ride along on a static
    # block (e.g. `rows` on a text block): only widgets show data, by reference.
    model_config = ConfigDict(frozen=True, extra="forbid")


class Heading(_Block):
    type: Literal["heading"]
    text: Annotated[str, Field(min_length=1, max_length=500)]
    level: Literal[1, 2, 3] = 2


class Text(_Block):
    """Plain text. A blank line separates paragraphs; there is no markup."""

    type: Literal["text"]
    text: Annotated[str, Field(min_length=1, max_length=MAX_TEXT)]


class Tone(StrEnum):
    NOTE = "note"
    FINDING = "finding"
    WARNING = "warning"


class Callout(_Block):
    type: Literal["callout"]
    tone: Tone = Tone.NOTE
    title: Annotated[str, Field(max_length=500)] = ""
    text: Annotated[str, Field(min_length=1, max_length=MAX_TEXT)]


class WidgetBlock(_Block):
    """Shows a widget at the report's run. In a report it names `widget_id`; in a template
    it names a `slot`, which a report made from the template fills with a widget."""

    type: Literal["widget"]
    widget_id: Id | None = None
    slot: Annotated[str, Field(min_length=1, max_length=200)] | None = None
    caption: Annotated[str, Field(max_length=2_000)] = ""


class Section(_Block):
    type: Literal["section"]
    title: Annotated[str, Field(max_length=500)] = ""
    blocks: tuple[Block, ...]


type Block = Annotated[
    Heading | Text | Callout | WidgetBlock | Section, Field(discriminator="type")
]

BLOCK_TYPES = ("heading", "text", "callout", "widget", "section")

_blocks = TypeAdapter(tuple[Block, ...])


class Tree(StrEnum):
    """What a tree belongs to, which decides how its widget blocks name their widget."""

    REPORT = "report"
    TEMPLATE = "template"


def parse(content: JsonObject, tree: Tree) -> tuple[Block, ...]:
    """The blocks of a tree a caller wrote, checked. Raises Invalid with every problem and
    where it is, e.g. `blocks[2].type`."""
    if not isinstance(content, dict):
        raise Invalid("The content must be an object with a `blocks` list")
    if SOURCES_KEY in content:
        raise Invalid(
            "`sources` is generated by the platform from the widgets' pipelines; leave it out"
        )
    unknown = sorted(set(content) - {BLOCKS_KEY})
    if unknown:
        raise Invalid(f"The content has unknown keys {unknown}; it holds only `blocks`")
    if BLOCKS_KEY not in content:
        raise Invalid("The content needs a `blocks` list")
    try:
        blocks = _blocks.validate_python(content[BLOCKS_KEY])
    except ValidationError as error:
        raise Invalid(_describe(error)) from None
    problems = list(_check(blocks, tree))
    if problems:
        raise Invalid("; ".join(problems))
    return blocks


def dump(blocks: Sequence[Block]) -> list[JsonObject]:
    """The stored JSON form: defaults filled in, so two equal trees store equally."""
    return list(_blocks.dump_python(tuple(blocks), mode="json", exclude_none=True))


def walk(blocks: Sequence[Block]) -> Iterator[Block]:
    """Every block, depth first, in reading order."""
    for block in blocks:
        yield block
        if isinstance(block, Section):
            yield from walk(block.blocks)


def widget_ids(blocks: Sequence[Block]) -> list[Id]:
    """The widgets a report shows, in reading order, each once."""
    seen: dict[Id, None] = {}
    for block in walk(blocks):
        if isinstance(block, WidgetBlock) and block.widget_id is not None:
            seen.setdefault(block.widget_id)
    return list(seen)


def slot_names(blocks: Sequence[Block]) -> list[str]:
    return [
        block.slot
        for block in walk(blocks)
        if isinstance(block, WidgetBlock) and block.slot is not None
    ]


def fill(blocks: Sequence[Block], widgets: dict[str, Id]) -> tuple[Block, ...]:
    """A template's tree with each slot replaced by the widget given for it."""

    def filled(block: Block) -> Block:
        if isinstance(block, Section):
            return block.model_copy(update={"blocks": tuple(filled(b) for b in block.blocks)})
        if isinstance(block, WidgetBlock) and block.slot is not None:
            return WidgetBlock(type="widget", widget_id=widgets[block.slot], caption=block.caption)
        return block

    return tuple(filled(block) for block in blocks)


def renamed(blocks: Sequence[Block], widgets: Mapping[Id, Id]) -> tuple[Block, ...]:
    """The tree with each widget block naming the widget `widgets` maps its widget to."""

    def named(block: Block) -> Block:
        if isinstance(block, Section):
            return block.model_copy(update={"blocks": tuple(named(b) for b in block.blocks)})
        if (
            isinstance(block, WidgetBlock)
            and block.widget_id is not None
            and block.widget_id in widgets
        ):
            return block.model_copy(update={"widget_id": widgets[block.widget_id]})
        return block

    return tuple(named(block) for block in blocks)


def stored_blocks(content: JsonObject) -> tuple[Block, ...]:
    """The blocks of a tree that was checked when it was stored."""
    return _blocks.validate_python(content.get(BLOCKS_KEY, []))


def _check(blocks: Sequence[Block], tree: Tree) -> Iterator[str]:
    count = 0
    for path, depth, block in _located(blocks, "blocks", 1):
        count += 1
        if depth > MAX_DEPTH:
            yield f"{path}: sections nest at most {MAX_DEPTH} deep"
        if isinstance(block, WidgetBlock):
            yield from _check_widget(path, block, tree)
    if count > MAX_BLOCKS:
        yield f"The tree has {count} blocks; at most {MAX_BLOCKS} are allowed"
    if tree is Tree.TEMPLATE:
        names = slot_names(blocks)
        for name in sorted({name for name in names if names.count(name) > 1}):
            yield f"The slot {name!r} appears more than once"


def _check_widget(path: str, block: WidgetBlock, tree: Tree) -> Iterator[str]:
    if tree is Tree.REPORT:
        if block.slot is not None:
            yield f"{path}: a report's widget block names a `widget_id`, not a `slot`"
        if block.widget_id is None:
            yield f"{path}: a widget block needs a `widget_id`"
    else:
        if block.widget_id is not None:
            yield (
                f"{path}: a template's widget block names a `slot`; put a default widget "
                "on the slot itself"
            )
        if block.slot is None:
            yield f"{path}: a template's widget block needs a `slot`"


def _located(blocks: Sequence[Block], prefix: str, depth: int) -> Iterator[tuple[str, int, Block]]:
    for index, block in enumerate(blocks):
        path = f"{prefix}[{index}]"
        yield path, depth, block
        if isinstance(block, Section):
            yield from _located(block.blocks, f"{path}.blocks", depth + 1)


def _describe(error: ValidationError) -> str:
    """pydantic's errors, worded for whoever wrote the tree, often an agent."""
    problems = []
    for item in error.errors():
        path = _path(item["loc"])
        match item["type"]:
            case "union_tag_invalid":
                tag = (
                    item.get("input", {}).get("type")
                    if isinstance(item.get("input"), dict)
                    else None
                )
                problems.append(
                    f"{path}: unknown component {tag!r}; use one of {', '.join(BLOCK_TYPES)}"
                )
            case "union_tag_not_found":
                problems.append(f"{path}: a block needs a `type`, one of {', '.join(BLOCK_TYPES)}")
            case "extra_forbidden":
                problems.append(
                    f"{path}: not a field of this block. Static blocks hold words only; "
                    "data is shown by widget blocks, by `widget_id`"
                )
            case _:
                problems.append(f"{path}: {item['msg']}")
    return "; ".join(problems)


def _path(loc: tuple[Any, ...]) -> str:
    # pydantic puts the union member's tag right after a block's index; it says nothing to
    # a reader. Only that position is a tag: `text` is also a field name.
    path = BLOCKS_KEY
    after_index = False
    for part in loc:
        if after_index and part in BLOCK_TYPES:
            after_index = False
            continue
        after_index = isinstance(part, int)
        path += f"[{part}]" if isinstance(part, int) else f".{part}"
    return path
