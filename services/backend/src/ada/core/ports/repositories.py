class AlertRepository(Protocol):
    async def get(self, id: Id) -> Alert: ...
    async def add(self, alert: Alert) -> None: ...

    async def save(self, alert: Alert) -> None:
        """Replace an alert's state. Alerts are written only by the alert check, one rule
        at a time, so they carry no revision."""
        ...

    async def find(self, rule_id: Id, key: JsonObject) -> Alert | None:
        """The firing alert for this rule and key, if there is one."""
        ...

    async def list(self, project_id: Id, state: AlertState | None = None) -> Sequence[Alert]:
        """Newest first."""
        ...
